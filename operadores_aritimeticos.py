# // divisão inteira
ni = 10 // 3
print ('10 // 3 = ', ni)

# % resto de divisão
ni = 10 % 3
print ('10 % 3 = ', ni)

# *mutiplicação
nr = 2.34 * 3.58
print ('2.34 * 3.58 = ', nr)

# / divisão fracionária
nr = 2.99 / 4.1
nrr = 2.99 % 4.1
print ('2.99 / 4.1 = ', nr)
print ('2.99 % 4.1 = ', nrr)

# ** exponenciação
ni = 2**3
print ('2**3 = ', ni)

#+ adição e - subtração
nr = (10.5 - 7.8) * (3.2 + 200.43)
print ('(10.5 - 7.8) * (3.2 + 200.43) = ', nr)